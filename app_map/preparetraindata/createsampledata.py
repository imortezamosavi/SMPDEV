def sampled_collection(imageCollection, pointCollection):
    image_ids = imageCollection.aggregate_array('id').getInfo()
    point_ids = pointCollection.aggregate_array('id').getInfo()

    common_ids = sorted(list(set(image_ids) & set(point_ids)))

    features = []

    for i, indx in tqdm(enumerate(common_ids), total=len(common_ids), desc="Sampling"):
        # Get the image and point with matching ID
        filtered_image = imageCollection.filter(ee.Filter.eq('id', indx)).first()
        filtered_point = pointCollection.filter(ee.Filter.eq('id', indx)).first()

        if filtered_image is None or filtered_point is None:
            print(f"No image or point found for ID: {indx}")
            continue

        geom = filtered_point.geometry()

        # Use reduceRegion to get band values (float precision)
        reduced = filtered_image.reduceRegion(
            reducer=ee.Reducer.first(),  # or mean, if more suitable
            geometry=geom,
            scale=10,
            maxPixels=1e9
        )

        # Add the values and metadata as a new feature
        feature = ee.Feature(geom).set(reduced).set({
            'doy': ee.Date(filtered_image.get('system:time_start')).getRelative('day', 'year'),
            'id': indx,
            'measure_moisture': filtered_point.get('measure_moisture')
        })

        features.append(feature)

    # Combine all into one FeatureCollection
    return ee.FeatureCollection(features)

def split_dataframe_by_days(df, day_chunk_size=40, output_prefix="output_chunk", output_dir=".", fallback_dir="fallback"):
    # Drop rows with missing values
    df_clean = df.dropna()

    # Select relevant columns
    selected_columns = ['Latitude', 'Longitude', 'Reading Time', 'Moisture']
    df_clean = df_clean[selected_columns]

    # Convert 'Reading Time' to datetime
    df_clean['Reading Time'] = pd.to_datetime(df_clean['Reading Time'], format='%Y-%m-%d %H:%M:%S', errors='coerce')
    df_clean = df_clean.dropna(subset=['Reading Time'])

    # Add timestamp and time info
    df_clean['time_ms'] = df_clean['Reading Time'].astype('int64') // 10**6
    df_clean['day'] = df_clean['Reading Time'].dt.date
    df_clean['hour'] = df_clean['Reading Time'].dt.strftime('%H:%M')

    # Get all unique days sorted
    unique_days = sorted(df_clean['day'].unique())

    if len(unique_days) <= day_chunk_size:
        # Save original file if not enough days
        fallback_dir = os.path.abspath(fallback_dir)
        if not os.path.exists(fallback_dir):
            os.makedirs(fallback_dir)

        fallback_path = os.path.join(fallback_dir, f"{output_prefix}_original.csv")
        df.to_csv(fallback_path, index=False)
        print(f"⚠️ Not enough unique days. Original file saved to: {fallback_path}")
        return 0

    # Ensure output directory exists
    output_dir = os.path.abspath(output_dir)
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)

    file_count = 0
    for i in range(0, len(unique_days), day_chunk_size):
        day_chunk = unique_days[i:i+day_chunk_size]
        chunk_df = df_clean[df_clean['day'].isin(day_chunk)]

        chunk_filename = os.path.join(output_dir, f"{output_prefix}_{file_count + 1}.csv")
        chunk_df.to_csv(chunk_filename, index=False)
        file_count += 1

    print(f"✅ Done! Created {file_count} CSV files based on 40-day chunks.")
    return file_count

