class IindexExtractor:
    def __init__(self, scale):
        self.scale = scale

    def optram(self, image):
        # Select bands and apply scaling factor
        bands = image.select('B.*').multiply(0.0001)

        # Compute NDVI and STR indices
        NDVI = bands.normalizedDifference(['B8', 'B4']).rename('ndvi')
        STR = bands.expression('((1 - swir) ** 2) / (2 * swir)', {'swir': bands.select('B12')}).rename('str')
        stack = ee.Image.cat([NDVI, STR])

        # Apply thresholds for full vegetation and bare soil
        thr_full = NDVI.gt(0.3)
        str_full = STR.updateMask(thr_full)

        thr_bare = NDVI.gte(0).And(NDVI.lt(0.2))
        str_bare = STR.updateMask(thr_bare)

        # Calculate VW, VD, IW, ID values over the region of interest
        vw = ee.Number(str_full.reduceRegion(
            reducer=ee.Reducer.max(),
            scale=self.scale
        ).get('str'))

        vd = ee.Number(str_full.reduceRegion(
            reducer=ee.Reducer.min(),
            scale=self.scale
        ).get('str'))

        iw = ee.Number(str_bare.reduceRegion(
            reducer=ee.Reducer.max(),
            scale=self.scale
        ).get('str'))

        id = ee.Number(str_bare.reduceRegion(
            reducer=ee.Reducer.min(),
            scale=self.scale
        ).get('str'))

        # Calculate SW and SD values
        sw = vw.subtract(iw)
        sd = vd.subtract(id)

        # Create the soil moisture index
        mask = NDVI.lt(-0.1).Not()
        index = stack.expression(
            '(id + sd * ndvi - str) / (id - iw + (sd - sw) * ndvi)',
            {
                'id': id,
                'sd': sd,
                'ndvi': NDVI,
                'str': STR,
                'iw': iw,
                'sw': sw
            }
        ).rename('OPTRM')

        # Return the final index with scaling and masking
        return index.updateMask(mask).copyProperties(image, image.propertyNames())

    def ndwi(self, image):

        NDWI = image.normalizedDifference(['B3', 'B8']).rename('NDWI')
        return NDWI

    def ndvi(self, image):

        NDVI = image.normalizedDifference(['B3', 'B8']).rename('NDVI')
        return NDVI

    def ndmi(self, image):

        NDMI = image.normalizedDifference(['B8', 'B11']).rename('NDMI');
        return NDMI

    def nsds(slef, image):
        NSDS = image.normalizedDifference(['B11', 'B12']).rename('NSDS');
        return NSDS

    def gvmi(self, image):
        # Implement GVMI formula
        GVMI = image.expression(
            '((nir + 0.1) - (swir + 0.02)) / ((nir + 0.1) + (swir + 0.02))',
            {
                'nir': image.select('B8'),
                'swir': image.select('B11')
            }
        ).rename('GVMI')
        return GVMI
    
def process_soil_data(file_path):
    """
    Load and process soil moisture data from a CSV file.

    Args:
        file_path (str): Path to the CSV file.

    Returns:
        pd.DataFrame: Processed DataFrame with additional columns.
        pd.DataFrame: DataFrame with unique day entries.
    """
    # Load the CSV
    df = pd.read_csv(file_path)

    df_clean = df.dropna()

    # Select relevant columns
    selected_columns = ['Latitude', 'Longitude', 'Reading Time', 'Moisture']
    df_clean = df_clean[selected_columns]

    # Convert 'Reading Time' to datetime format
    df_clean['Reading Time'] = pd.to_datetime(df_clean['Reading Time'], format='%Y-%m-%d %H:%M:%S')

    # Add Unix timestamp in milliseconds
    df_clean['time_ms'] = df_clean['Reading Time'].astype('int64') // 10**6

    # Extract date and time features
    df_clean['day'] = df_clean['Reading Time'].dt.date
    df_clean['hour'] = df_clean['Reading Time'].dt.strftime('%H:%M')

    # Get one record per day per location
    df_unique_day = df_clean.drop_duplicates(subset=['Latitude', 'Longitude', 'day'], keep='first')

    return df_clean, df_unique_day

def create_feature_collection(df):
    """
    Create a FeatureCollection from a DataFrame.

    Args:
        df (pd.DataFrame): Input DataFrame.

    Returns:
        ee.FeatureCollection: FeatureCollection created from the DataFrame.
    """ 
    pointFeatures = []
    # Iterate through the DataFrame's index
    for i, idx in enumerate(df.index): 
        row = df.loc[idx] # Use .loc to access row by index label
        point = ee.Geometry.Point([row['Longitude'], row['Latitude']])
        reading_day = ee.Date(str(row['day']))
        moisture = row['Moisture']

        feature = ee.Feature(point).set({
            'measure_moisture': moisture,
            'startDate': reading_day.advance(-1, 'day'),
            'endDate': reading_day.advance(1, 'day'),
            'id': i + 1,
            'latitude': point.coordinates().get(1),
            'longitude': point.coordinates().get(0)
        })

        pointFeatures.append(feature)

    return ee.FeatureCollection(pointFeatures)

def add_indices(image):
    # Instantiate IindexExtractor with the region of interest and scale
    index_extractor = IindexExtractor(10)

    # Compute indices using the instance of IindexExtractor
    optram_index = index_extractor.optram(image)
    ndwi_index = index_extractor.ndwi(image)
    ndvi_index = index_extractor.ndvi(image)
    ndmi_index = index_extractor.ndmi(image)
    nsds_index = index_extractor.nsds(image)
    gvmi_index = index_extractor.gvmi(image)

    # Add computed indices as new bands to the original image
    # return image.addBands([optram_index, ndwi_index, ndvi_index, ndmi_index, nsds_index, gvmi_index])
    return image.addBands([ndwi_index, ndvi_index, ndmi_index, nsds_index, gvmi_index])

def collect_images(feature):
    # Get the geometry (point) and date range from the feature
    point = feature.geometry()
    start = ee.Date(feature.get('startDate'))
    end = ee.Date(feature.get('endDate'))
    id = feature.get('id')

    # Filter Sentinel-2 collection by point and date range
    image_collection = ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED') \
        .filterBounds(point) \
        .filterDate(start, end) \
        .sort('CLOUDY_PIXEL_PERCENTAGE') \
        .select("B.*") \
        .map(add_indices)  # Assuming add_indices is defined elsewhere

    # Add startDate, endDate, and id properties to each image in the collection
    image_collection = image_collection.map(lambda image: image.set({
        'point_geometry':point,
        'startDate': start,
        'endDate': end,
        'id': id,
        'doy': ee.Date(image.get('system:time_start')).getRelative('day', 'year')
    }))

    # Select the least cloudy image (first in the sorted collection)
    # image = image_collection.first().toFloat()
    image = image_collection.first()

    # Check if an image exists, return the image as a collection or an empty collection
    return ee.Algorithms.If(image, ee.ImageCollection(image.toFloat()), ee.ImageCollection([]))

def find_best_time(imageCollection, df):
    """
    For each Earth Engine timestamp, find the closest row in the DataFrame based on 'time_ms'.

    Args:
        df (pd.DataFrame): DataFrame with a 'time_ms' column.
        images_info (list of dicts): List of dictionaries with 'id' and 'time_ms' for each image from Earth Engine.

    Returns:
        pd.DataFrame: Rows from df that are closest in time to each Earth Engine timestamp, along with the image ID.
    """

    # Get list of timestamps and IDs from Earth Engine
    image_times = imageCollection.aggregate_array('system:time_start').getInfo()
    image_ids = imageCollection.aggregate_array('id').getInfo()

    # Combine into list of dictionaries
    images_info = [{'id': img_id, 'time_ms': ts} for img_id, ts in zip(image_ids, image_times)]

    matched_rows = []

    for img_info in images_info:
        ts = img_info['time_ms']  # Extract the timestamp (time_ms)
        image_id = img_info['id']  # Extract the image ID

        # Compute the absolute difference and find the index of the closest row
        closest_idx = (df['time_ms'] - ts).abs().idxmin()

        # Get the closest row and copy it to avoid SettingWithCopyWarning
        closest_row = df.loc[closest_idx].copy()
        closest_row['image_id'] = image_id  # Add the image ID to the copied row

        # Append the corresponding row with the image ID
        matched_rows.append(closest_row)

    # Combine into a DataFrame and reset index
    return pd.DataFrame(matched_rows).reset_index(drop=True)

